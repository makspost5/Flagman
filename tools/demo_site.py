"""Build the live demo site: the page plus a data script that replays a scenario.

    python tools/demo_site.py [OUT_DIR]      (default: _site)

The page is plugin/page/taskgraph.html as is. Its data file, taskgraph.js, holds every step
of examples/demo/scenario.txt, recorded by running the scenario's commands with the real fm
on a copy of examples/demo/taskgraph.js. The page reloads taskgraph.js every few seconds;
each load picks the step for the current time, so the graph changes by itself, then the
scenario starts again. No server code: GitHub Pages hosts the folder as is.
"""
from __future__ import annotations

import io
import json
import shlex
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "plugin" / "scripts"))

from taskgraph import cli, model, store  # noqa: E402

DEMO = ROOT / "examples" / "demo"
PAGE = ROOT / "plugin" / "page" / "taskgraph.html"
REPO_URL = "https://github.com/makspost5/Flagman"
STEP_MS = 4500   # one scenario step
END_MS = 9000    # the last step stays this long before the scenario starts again


def parse_scenario(text: str) -> list[tuple[str, list[str]]]:
    """[(caption, [fm command, ...]), ...] from "> caption" lines and the fm lines under them."""
    steps: list[tuple[str, list[str]]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(">"):
            steps.append((line[1:].strip(), []))
        elif line.startswith("fm ") and steps:
            steps[-1][1].append(line)
        else:
            raise ValueError(f"scenario: unexpected line: {raw!r}")
    if not steps:
        raise ValueError("scenario: no steps")
    return steps


def record(scenario: str) -> list[dict]:
    """Run the scenario on a copy of the demo graph; one {caption, graph} per step."""
    frames = []
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp) / ".tasks" / "SHOP-1"
        folder.mkdir(parents=True)
        shutil.copy(DEMO / "taskgraph.js", folder / "taskgraph.js")
        for caption, commands in parse_scenario(scenario):
            for line in commands:
                err = io.StringIO()
                code = cli.main(shlex.split(line)[1:], cwd=tmp, out=io.StringIO(), err=err)
                if code != 0:
                    raise RuntimeError(f"scenario command failed: {line}\n{err.getvalue()}")
            graph = store.load(folder)
            problems = model.validate(graph)
            if problems:
                raise RuntimeError(f"scenario step {caption!r} left a broken graph: {problems}")
            frames.append({"caption": caption, "graph": graph})
    return frames


PLAYER = r"""// Live demo data for the Flagman page, generated by tools/demo_site.py from
// examples/demo/scenario.txt. The page loads this file again every few seconds; each load
// picks the scenario step for the current time, so the graph plays out by itself.
(function () {
  var STEPS = __STEPS__;
  var STEP_MS = __STEP_MS__, END_MS = __END_MS__, REPO = __REPO__;
  var CYCLE = (STEPS.length - 1) * STEP_MS + END_MS;
  var d = window.FM_DEMO || (window.FM_DEMO = { start: Date.now(), shown: {} });
  var run = Date.now() - d.start;
  var loop = Math.floor(run / CYCLE), t = run % CYCLE;
  var i = Math.min(STEPS.length - 1, Math.floor(t / STEP_MS));
  // ?step=N shows step N and stays there (for links and the README GIF).
  var fixed = /[?&]step=(\d+)/.exec(location.search);
  if (fixed) { loop = 0; i = Math.max(0, Math.min(STEPS.length - 1, parseInt(fixed[1], 10) - 1)); }
  var key = loop + ":" + i;

  // "updated" on the page: the moment this step first showed.
  if (!d.shown[key]) d.shown[key] = new Date();
  function pad(n) { return (n < 10 ? "0" : "") + n; }
  var w = d.shown[key];
  var g = JSON.parse(JSON.stringify(STEPS[i].graph));
  g.task.updated = w.getFullYear() + "-" + pad(w.getMonth() + 1) + "-" + pad(w.getDate()) +
    "T" + pad(w.getHours()) + ":" + pad(w.getMinutes());
  g.task.rev = loop * STEPS.length + i + 1; // a new rev makes the page redraw
  window.TASKGRAPH = g;

  function bar() {
    var b = document.getElementById("fm-demo");
    if (!b) {
      b = document.createElement("div");
      b.id = "fm-demo";
      b.setAttribute("role", "status");
      b.style.cssText = "position:fixed;left:16px;right:16px;bottom:56px;margin:0 auto;width:fit-content;max-width:900px;" +
        "z-index:50;box-sizing:border-box;display:flex;flex-wrap:wrap;gap:6px 12px;align-items:center;" +
        "padding:10px 16px;border-radius:10px;background:rgba(22,26,34,.92);color:#fff;" +
        "font:13px/1.4 system-ui,-apple-system,'Segoe UI',sans-serif;box-shadow:0 4px 16px rgba(0,0,0,.25)";
      b.innerHTML = '<b>Live demo</b><span id="fm-demo-step" style="opacity:.75"></span>' +
        '<span id="fm-demo-caption" style="flex:0 1 auto;min-width:200px"></span>' +
        '<button id="fm-demo-restart" type="button" style="font:inherit;color:inherit;background:none;' +
        'border:1px solid rgba(255,255,255,.4);border-radius:6px;padding:2px 10px;cursor:pointer">Restart</button>' +
        '<a href="' + REPO + '" style="color:#9cc3ff">GitHub</a>';
      document.body.appendChild(b);
      document.getElementById("fm-demo-restart").addEventListener("click", function () {
        if (fixed) { location.search = ""; return; }
        window.FM_DEMO = { start: Date.now(), shown: {} };
        var s = document.createElement("script");
        s.src = "taskgraph.js?t=" + Date.now();
        document.head.appendChild(s);
      });
    }
    document.getElementById("fm-demo-step").textContent = "step " + (i + 1) + " of " + STEPS.length;
    document.getElementById("fm-demo-caption").textContent = STEPS[i].caption;
  }
  if (document.body) bar(); else document.addEventListener("DOMContentLoaded", bar);
})();
"""


def player_js(frames: list[dict]) -> str:
    js = PLAYER
    for key, value in (("__STEPS__", json.dumps(frames, ensure_ascii=False, separators=(",", ":"))),
                       ("__STEP_MS__", str(STEP_MS)), ("__END_MS__", str(END_MS)),
                       ("__REPO__", json.dumps(REPO_URL))):
        js = js.replace(key, value)
    # keep "</script>" in the data from closing anything if the file is ever inlined
    return js.replace("</", "<\\/")


def build(out: Path) -> list[dict]:
    frames = record((DEMO / "scenario.txt").read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(PAGE, out / "index.html")
    (out / "taskgraph.js").write_text(player_js(frames), encoding="utf-8", newline="\n")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    return frames


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else ROOT / "_site"
    frames = build(out)
    print(f"ok: {out} ({len(frames)} steps)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
